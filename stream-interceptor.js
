// stream-interceptor.js - Core Ingestion & Validation Engine for Aegis
const AegisStreamInterceptor = {
    // Actively ingest an incoming data stream packet
    async processIncomingStream(packet) {
        console.log("[VIGIL] Stream Intercepted. Analyzing origin metadata...");
        
        // 1. Extract payload and security signature
        const rawPayload = typeof packet.payload === 'string' ? packet.payload : JSON.stringify(packet.payload);
        const providedHash = packet.expectedHash;

        // 2. Route straight to the hardware-enforced Validator Agent
        console.log("[VALIDATOR] Invoking Web Crypto SHA-256 engine...");
        const calculatedHash = await this.generateHardwareHash(rawPayload);

        if (calculatedHash === providedHash) {
            return {
                status: "VERIFIED_GROUND_TRUTH",
                authenticityScore: "100%",
                hash: calculatedHash,
                timestamp: new Date().toISOString()
            };
        } else {
            // 3. If hashes mismatch, instantly invoke the Gemini Deep Contextual Analysis Sub-Module
            console.warn("[VALIDATOR] CRITICAL HASH MISMATCH DETECTED. Routing to Gemini AI Studio...");
            const aiAnalysis = await this.invokeAIStudioAnalysis(rawPayload, calculatedHash, providedHash);
            
            return {
                status: "UNVERIFIED_ANOMALY",
                authenticityScore: "0%",
                hashDetected: calculatedHash,
                expected: providedHash,
                telemetry: aiAnalysis,
                timestamp: new Date().toISOString()
            };
        }
    },

    // Native Browser Hardware Hashing
    async generateHardwareHash(text) {
        const encoder = new TextEncoder();
        const data = encoder.encode(text);
        const hashBuffer = await crypto.subtle.digest('SHA-256', data);
        const hashArray = Array.from(new Uint8Array(hashBuffer));
        return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
    },

    // Direct v1beta API Context Analyzer
    async invokeAIStudioAnalysis(payload, liveHash, expectedHash) {
        // Pulls directly from your configured v1beta endpoint structure
        try {
            const response = await fetch('https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-pro:generateContent', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    contents: [{
                        parts: [{
                            text: `ANOMALY REPORT: A cryptographic data tamper has occurred.\nRaw Payload: ${payload}\nCalculated Hash: ${liveHash}\nExpected Signature: ${expectedHash}\nAnalyze this payload for deep structural manipulation, machine insertion, or synthetic anomalies. Return a strict JSON compliance log.`
                        }]
                    }],
                    generationConfig: {
                        temperature: 0.1,
                        responseMimeType: "application/json"
                    }
                })
            });
            const data = await response.json();
            return data;
        } catch (err) {
            return { error: "AI_STUDIO_DISCONNECT", details: err.message };
        }
    }
};
